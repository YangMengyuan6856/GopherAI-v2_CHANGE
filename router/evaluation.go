package router

import (
	evaluationcontroller "GopherAI/controller/evaluation"

	"github.com/gin-gonic/gin"
)

func RegisterEvaluationRouter(group *gin.RouterGroup) {
	handler := evaluationcontroller.NewDefaultHandler()
	memoryHandler := evaluationcontroller.NewDefaultMemoryHandler()
	contextHandler := evaluationcontroller.NewDefaultContextHandler()
	toolHandler := evaluationcontroller.NewDefaultToolHandler()
	collaborationHandler := evaluationcontroller.NewDefaultCollaborationHandler()
	parentContextHandler := evaluationcontroller.NewDefaultParentContextHandler()
	catalogHandler := evaluationcontroller.NewDefaultCatalogHandler()
	unifiedHandler := evaluationcontroller.NewDefaultUnifiedHandler()
	anomalyHandler := evaluationcontroller.NewAnomalyHandler()
	metricCatalogHandler := evaluationcontroller.NewDefaultMetricCatalogHandler()
	prometheusRuntimeHandler := evaluationcontroller.NewDefaultPrometheusRuntimeHandler()
	grafanaRuntimeHandler := evaluationcontroller.NewDefaultGrafanaRuntimeHandler()
	controlWebhookHandler := evaluationcontroller.NewDefaultControlWebhookHandler()
	recommendationHandler := evaluationcontroller.NewDefaultRecommendationHandler()
	faultCampaignHandler := evaluationcontroller.NewDefaultFaultCampaignHandler()
	onlineEvaluationHandler := evaluationcontroller.NewDefaultOnlineEvaluationHandler()
	failurePoolHandler := evaluationcontroller.NewDefaultFailurePoolHandler()
	reliabilityHandler := evaluationcontroller.NewDefaultReliabilityHandler()
	evolutionHandler := evaluationcontroller.NewDefaultEvolutionHandler()
	evolutionComparisonHandler := evaluationcontroller.NewDefaultEvolutionComparisonHandler()
	performanceHandler := evaluationcontroller.NewDefaultPerformanceHandler()
	pairedHandler := evaluationcontroller.NewDefaultPairedHandler()
	judgeCalibrationHandler := evaluationcontroller.NewDefaultJudgeCalibrationHandler()
	interviewEvidenceHandler := evaluationcontroller.NewDefaultInterviewEvidenceHandler()
	group.GET("/diagnostic/latest", handler.LatestDiagnostic)
	group.GET("/memory/latest", memoryHandler.LatestMemory)
	group.GET("/context/latest", contextHandler.LatestContext)
	group.GET("/tools/latest", toolHandler.LatestTool)
	group.GET("/collaboration/latest", collaborationHandler.Latest)
	group.GET("/parent-context/latest", parentContextHandler.Latest)
	group.GET("/catalog/latest", catalogHandler.Latest)
	group.GET("/unified/latest", unifiedHandler.Latest)
	group.POST("/anomaly/simulate", anomalyHandler.Simulate)
	group.GET("/anomaly/production/latest", anomalyHandler.ProductionLatest)
	group.GET("/metrics/catalog", metricCatalogHandler.Latest)
	group.GET("/metrics/runtime", prometheusRuntimeHandler.Latest)
	group.GET("/metrics/dashboard", grafanaRuntimeHandler.Latest)
	group.GET("/webhooks/latest", controlWebhookHandler.Latest)
	group.POST("/webhooks/acceptance", controlWebhookHandler.Acceptance)
	group.GET("/controller/latest", recommendationHandler.Latest)
	group.POST("/controller/acceptance", recommendationHandler.Acceptance)
	group.GET("/fault-campaigns/latest", faultCampaignHandler.Latest)
	group.POST("/fault-campaigns/acceptance", faultCampaignHandler.Acceptance)
	group.GET("/online/latest", onlineEvaluationHandler.Latest)
	group.POST("/online/acceptance", onlineEvaluationHandler.Acceptance)
	group.GET("/failure-pool/latest", failurePoolHandler.Latest)
	group.POST("/failure-pool/refresh", failurePoolHandler.Refresh)
	group.POST("/failure-pool/acceptance", failurePoolHandler.Acceptance)
	group.POST("/reliability/acceptance", reliabilityHandler.Acceptance)
	group.GET("/reliability/latest", reliabilityHandler.Latest)
	group.GET("/evolution/latest", evolutionHandler.Latest)
	group.POST("/evolution/materialize", evolutionHandler.Materialize)
	group.GET("/evolution/splits/latest", evolutionHandler.SplitsLatest)
	group.POST("/evolution/splits/acceptance", evolutionHandler.SplitsAcceptance)
	group.GET("/evolution/comparison/latest", evolutionComparisonHandler.Latest)
	group.POST("/evolution/comparison/run", evolutionComparisonHandler.Run)
	group.GET("/performance/latest", performanceHandler.Latest)
	group.GET("/paired/latest", pairedHandler.Latest)
	group.GET("/judge-calibration/latest", judgeCalibrationHandler.Latest)
	group.POST("/judge-calibration/reviews", judgeCalibrationHandler.Review)
	group.GET("/interview-evidence/latest", interviewEvidenceHandler.Latest)
}
